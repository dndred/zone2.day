-- zone2.day: strength log (docs/03-data-model.md §2.6). Sets are logged on the phone in the gym
-- (offline, sent through the outbox) or written by the coach via MCP (log_strength_session).
-- No times or rest: only what was done.

create table zone2.exercises (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references zone2.users(id) on delete cascade,
  name text not null,
  aliases text[] not null default '{}',     -- other names merged into this one (merge_exercises)
  created_at timestamptz not null default now()
);
create unique index exercises_user_name_idx on zone2.exercises (user_id, lower(name));

create table zone2.strength_sessions (
  id uuid primary key,                      -- generated by the client (idempotency)
  user_id uuid not null references zone2.users(id) on delete cascade,
  planned_workout_id text,
  date date not null,
  notes text,
  source text not null check (source in ('app', 'ai')),
  version int not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index strength_sessions_user_date_idx on zone2.strength_sessions (user_id, date);
create index strength_sessions_planned_idx on zone2.strength_sessions (user_id, planned_workout_id) where deleted_at is null;

create table zone2.strength_sets (
  id uuid primary key,                      -- generated by the client
  user_id uuid not null references zone2.users(id) on delete cascade,
  session_id uuid not null references zone2.strength_sessions(id) on delete cascade,
  exercise_id uuid not null references zone2.exercises(id),
  ord int not null,                         -- exercise order in the session
  set_index int not null,                   -- 0-based within the exercise
  planned jsonb,                            -- {reps, weightKg, holdSec, rpe}
  actual jsonb,                             -- {reps, weightKg, holdSec}; null = not done
  rpe numeric,
  note text,
  logged_at timestamptz not null default now(),
  source text not null check (source in ('app', 'ai')),
  deleted_at timestamptz
);
create index strength_sets_session_idx on zone2.strength_sets (session_id);
create index strength_sets_exercise_idx on zone2.strength_sets (user_id, exercise_id);

do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on all tables in schema zone2 from %I', r);
    end if;
  end loop;
end $$;
